def test_run_candidate_unknown_strategy_fail_closed_zero_retrieval(monkeypatch):
    calls = []

    def _forbid(*args, **kwargs):
        calls.append(1)
        raise AssertionError("must not retrieve for unknown strategy")

    monkeypatch.setattr("src.retrieval_ablation.retrieve_variant_lists",
                        _forbid)
    with pytest.raises(ValueError):
        run_candidate_retrieval(
            [{"case_id": "c1", "query": "A", "query_type": "single_fact",
              "language": "en", "should_refuse": False,
              "relevant_chunk_ids": [], "relevant_source_ids": []}],
            FAKE_INDEX, strategy="bogus",
        )
    assert calls == []  # 未知策略在检索之前就失败


# ── Group 4: runner against the baseline shape ────────────────────────

def test_single_query_strategy_matches_baseline_rows_byte_identical():
    cases = [
        {"case_id": "en-001", "query": "compare topic-3 and topic-5",
         "query_type": "cross_document", "language": "en",
         "should_refuse": False,
         "relevant_chunk_ids": ["c03", "c05"],
         "relevant_source_ids": ["name-03"]},
        {"case_id": "zh-002", "query": "无真值观察", "query_type": "no_answer",
         "language": "zh", "should_refuse": True,
         "relevant_chunk_ids": [], "relevant_source_ids": []},
    ]
    baseline = _run_baseline_rows(cases, FAKE_INDEX, _fake_retrieve)
    candidate = run_candidate_retrieval(
        cases, FAKE_INDEX, strategy="single-query", retrieve_fn=_fake_retrieve)
    assert len(candidate) == len(baseline) == 2
    for b, c in zip(baseline, candidate):
        for key in b:
            assert c[key] == b[key], f"field {key} drifted in {c['case_id']}"
        assert c["strategy"] == "single-query"
        assert c["variants"] == [c["query"]]


def test_candidate_rows_unique_chunk_ids_full_metadata_and_provenance():
    cases = [
        {"case_id": "cd-001",
         "query": "Compare topic-3 and topic-5. 哪个更常用？",
         "query_type": "cross_document", "language": "mixed",
         "should_refuse": False,
         "relevant_chunk_ids": ["c03", "c05"],
         "relevant_source_ids": ["name-03"]},
    ]
    rows = run_candidate_retrieval(
        cases, FAKE_INDEX, strategy="mechanical-clause-rrf",
        retrieve_fn=_fake_retrieve)
    row = rows[0]
    # 无重复 chunk id
    assert len(row["retrieved_chunk_ids"]) == len(set(row["retrieved_chunk_ids"]))
    # variants：完整 query 优先 + 全为字面子串
    assert row["variants"][0] == row["query"]
    for v in row["variants"]:
        assert v in row["query"]
    # provenance：每个结果保留 source/citation metadata + variant 来源
    assert row["fusion"]["tie_break"] == "chunk_id_asc"
    by_id = {p["chunk_id"]: p for p in row["provenance"]}
    for cid in row["retrieved_chunk_ids"][:5]:
        p = by_id[cid]
        assert p["source_id"]
        assert p["source_path"]
        assert p["source_name"]
        assert p["variant_ranks"]
    # retrieved_source_ids 与 baseline 同构（source_name 首现序）
    assert row["retrieved_source_ids"]
    # 指标存在（有真值时）
    assert row["metrics"]["recall@5"] >= 0.0


